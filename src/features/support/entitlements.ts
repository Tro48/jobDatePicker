/**
 * Что человек купил.
 *
 * Сейчас — ничего и купить нечего: продавать отключение рекламы без ИП нельзя,
 * а без рекламы и отключать нечего. Интерфейс заведён заранее, потому что
 * покупка касается сразу трёх вещей — слота на «Сводке», настроек и
 * восстановления покупки на новом телефоне, — и разносить её по экранам потом
 * дороже, чем описать один раз сейчас.
 *
 * Реализация поверх RuStore Billing встанет на это же место: слот спрашивает
 * «куплено ли», а не «какой у нас биллинг».
 */
export interface Entitlements {
  /** Куплено ли отключение рекламы. */
  adsRemoved: () => boolean;
  /**
   * Покупка на новом телефоне. Возвращает, нашлась ли она. Заглушка отвечает
   * «нет» и ничего не делает.
   */
  restore: () => Promise<boolean>;
}

export const entitlements: Entitlements = {
  adsRemoved: () => false,
  restore: async () => false,
};

/**
 * Куда ведёт кнопка «Поддержать». null — вести пока некуда: страницы сбора
 * нет, ИП нет.
 *
 * Строка, а не функция: адрес появится правкой одной константы и уедет к людям
 * обновлением по воздуху, без сборки APK.
 */
export const SUPPORT_URL: string | null = null;
