import type { ReactNode } from 'react';

/**
 * Реклама. Сейчас — только форма, без содержимого.
 *
 * SDK в сборку намеренно не кладётся: он начинает собирать идентификаторы
 * устройства с первого запуска, а это политика конфиденциальности, декларация
 * рекламного идентификатора в RuStore и уведомление в Роскомнадзор — ради
 * функции, которую неизвестно когда включат. Цена решения — одна лишняя
 * нативная сборка потом, когда включат.
 *
 * Интерфейс живёт уже сейчас, чтобы место вставки было ровно одно и чтобы
 * появление рекламы не растеклось по экранам: слот спрашивает провайдера, есть
 * ли что показывать, и рисует то, что тот вернул.
 */
export interface AdProvider {
  /** Есть ли что показать прямо сейчас. Заглушка всегда отвечает «нет». */
  isAvailable: () => boolean;
  /** Готовый блок. null — показывать нечего, слот берёт карточку поддержки. */
  render: () => ReactNode;
}

/**
 * Провайдер этой сборки. Всегда пустой: рекламного SDK в приложении нет, и
 * слот из-за него ничего не рисует.
 */
export const adProvider: AdProvider = {
  isAvailable: () => false,
  render: () => null,
};
