/**
 * Что изменилось в выпусках — список для шторки «Что нового».
 *
 * Записи опознаются датой, а не версией приложения: версию поднимает CI уже
 * после мержа, и в момент, когда пишется эта строка, её ещё не существует.
 *
 * Ни React, ни React Native здесь нет намеренно: тот же список читает сборка,
 * чтобы положить заголовок последней записи в список выпусков — телефону со
 * старым JS взять текст про новую сборку больше неоткуда.
 *
 * Порядок — от свежего к старому, это проверяется тестом.
 */
export interface ReleaseNote {
  /** Дата выпуска в формате YYYY-MM-DD. Она же идентификатор записи. */
  id: string;
  /** Одна строка о главном: она уходит в список выпусков и в полоску календаря. */
  title: string;
  /** Подробности, по пункту на изменение. */
  items: string[];
}

export const RELEASE_NOTES: ReleaseNote[] = [
  {
    id: '2026-09-03',
    title: 'Видно, сколько уже отработано',
    items: [
      'Сводка и строка под календарём показывают смены и часы дробью: сколько отработано из запланированного на месяц.',
      'Отработанные смены в календаре приглушены.',
      'День, где часы разошлись с графиком, помечен точкой: зелёной при переработке, красной при недоработке. Под календарём — итог за месяц.',
      'Смена и тип выплаты в карточке дня выбираются выпадающим списком — карточка стала короче.',
    ],
  },
];

/** Самая свежая запись. null — списка ещё нет. */
export const LATEST_RELEASE_ID: string | null = RELEASE_NOTES[0]?.id ?? null;

/**
 * Записи, которых человек ещё не видел.
 *
 * null вместо отметки — это обновление с прошлой схемы хранилища: показываем
 * всё, что накопилось. У новой установки отметка сразу стоит на свежей записи,
 * и «что нового» ей не показывается: человеку, который только поставил
 * приложение, нечего рассказывать про изменения.
 */
export function unseenReleases(lastSeenId: string | null): ReleaseNote[] {
  if (lastSeenId === null) return RELEASE_NOTES;
  return RELEASE_NOTES.filter((note) => note.id > lastSeenId);
}
