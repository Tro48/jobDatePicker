import type { IsoDate, Weekday } from './date.ts';

/**
 * Тип дня в графике. Смена — не только «работа/не работа»: отсыпной после
 * ночной и обычный выходной различаются визуально и в сводке, поэтому это
 * отдельные записи справочника, а не флаг.
 */
export type ShiftKind = 'work' | 'rest';

export interface ShiftType {
  id: string;
  /** Полное название для списков и озвучки скринридером. */
  name: string;
  /**
   * Однобуквенный маркер в клетке календаря. Обязателен: смысл дня не должен
   * передаваться одним лишь цветом.
   */
  badge: string;
  kind: ShiftKind;
  /** Токен палитры, а не готовый цвет — значение подставляет активная тема. */
  colorToken: string;
  /** Только для kind === 'work'. */
  time?: {
    /** "HH:MM" */
    start: string;
    /** "HH:MM". Меньше start — смена переходит через полночь. */
    end: string;
    /** Неоплачиваемый перерыв, вычитается из отработанных часов. */
    unpaidBreakMinutes: number;
  };
  /** Надбавка за смену: ночная ×1.2 и т.п. Применяется к почасовой ставке. */
  rateMultiplier: number;
  /**
   * Ставится сразу на несколько дней подряд: отпуск, больничный. Карточка дня
   * спрашивает у таких количество дней, а не проставляет один.
   */
  multiDay?: boolean;
}

/**
 * Как график раскладывается по датам. Два генератора закрывают все текущие
 * варианты; новый график добавляется записью в справочнике пресетов, а не
 * кодом. Третий вид (например, привязка к производственному календарю)
 * добавляется новым вариантом этого union и одной веткой в resolvePlannedShift.
 */
export type SchedulePattern =
  /**
   * Цикл фиксированной длины от даты первой смены: 2/2, 3/3, ДНОВ,
   * «сутки-трое». slots[i] — id типа смены на i-й день цикла.
   */
  | { kind: 'cycle'; slots: string[] }
  /**
   * Привязка к дням недели. weeks — чередующиеся недели: одна запись это
   * обычная пятидневка, две — «через субботу», и так далее.
   */
  | { kind: 'weekly'; weeks: Array<Record<Weekday, string>> };

export interface SchedulePreset {
  id: string;
  name: string;
  /** Короткое пояснение под названием в списке выбора. */
  description: string;
  pattern: SchedulePattern;
}

/** График, выбранный пользователем, вместе с точкой отсчёта. */
export interface ActiveSchedule {
  presetId: string;
  pattern: SchedulePattern;
  /**
   * Для cycle — дата первой смены (slots[0]).
   * Для weekly — любая дата первой недели цикла; для одной недели не влияет ни на что.
   */
  anchorDate: IsoDate;
}

/** Ручная правка поверх графика: незапланированный выходной или подработка. */
export interface DayOverride {
  date: IsoDate;
  shiftTypeId: string;
  /** Фактические часы, если смена вышла не штатной длины. */
  workedMinutesOverride?: number;
  note?: string;
}

/** День календаря после наложения правок на график. */
export interface ResolvedDay {
  date: IsoDate;
  shiftType: ShiftType;
  source: 'schedule' | 'override';
  /** Оплачиваемые минуты: 0 для выходных. */
  workedMinutes: number;
  note?: string;
}

/**
 * Деньги в приложении — только факт. Приложение ничего не «начисляет»:
 * пользователь вносит полученные суммы, а ставка за час и за смену выводится
 * делением суммы за месяц на отработанные часы и смены этого месяца.
 */
export type PaymentKind = 'advance' | 'salary';

/**
 * Когда ожидать выплату. Нужно только для подсказки «аванс через 3 дня» и для
 * предзаполнения даты в форме ввода — на расчёты не влияет.
 */
export interface PaymentRule {
  kind: PaymentKind;
  /** День месяца, в который приходит выплата. */
  dayOfMonth: number;
  /**
   * В каком месяце приходит выплата относительно месяца, ЗА который платят:
   * -1 — раньше (аванс за сентябрь приходит в конце августа),
   *  0 — в том же месяце,
   * +1 — позже (зарплата за сентябрь приходит в октябре).
   */
  paidInMonthOffset: -1 | 0 | 1;
  /** Куда сдвинуть дату, если она выпала на субботу или воскресенье. */
  weekendShift: 'before' | 'after' | 'none';
}

export interface PayrollSettings {
  currency: string;
  rules: PaymentRule[];
  /**
   * Для незакрытого месяца показывать прогноз, домножая уже отработанные часы
   * на ставку последнего закрытого месяца. Всегда помечается как прогноз.
   */
  forecastFromLastClosedMonth: boolean;
}

/** Фактически полученная сумма, введённая руками. */
export interface PaymentRecord {
  id: string;
  kind: PaymentKind;
  /**
   * Месяц, ЗА который выплата, в формате "YYYY-MM". Ключ всей денежной сводки:
   * аванс за сентябрь остаётся сентябрьским, даже если пришёл 27 августа.
   */
  period: string;
  /** Дата фактического поступления. */
  receivedOn: IsoDate;
  amount: number;
  note?: string;
}
